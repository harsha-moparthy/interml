// Browser check for article pages. Run the servers against app/e2e/fixtures (see app/e2e/README.md).
import { chromium } from "playwright-core";
const PORT = process.env.WEB_PORT || 5173;
const exe = "/mnt/nas/harshamttl/.cache/ms-playwright/chromium-1148/chrome-linux/chrome";
const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const p = await b.newPage({ viewport: { width: 1000, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const ok = (c, msg) => { console.log((c ? "PASS " : "FAIL ") + msg); if (!c) process.exitCode = 1; };
const base = "http://127.0.0.1:" + PORT + "/";
await p.goto(base + "#/question/30");
await p.waitForSelector("#learn-h");
ok((await p.locator("#learn-h ~ ul a").innerText()) === "Pairwise differences", "question 030 lists its lesson");
await p.click("#learn-h ~ ul a");
await p.waitForSelector("h1:has-text('Pairwise differences')");
ok((await p.locator(".meta").innerText()).includes("Complete"), "complete lesson is labelled Complete");
ok((await p.locator(".prereq a").innerText()) === "Broadcasting", "prerequisite link shown");
await p.click(".prereq a");
await p.waitForSelector("h1:has-text('Broadcasting')");
ok((await p.locator(".katex").count()) >= 2, "equations rendered (display + inline in caption)");
ok((await p.locator("img").getAttribute("alt")) === "A box labelled shape (2, 1, 3)", "image has alt text");
ok(await p.evaluate(() => { const i = document.querySelector("img"); return i.complete && i.naturalWidth > 0; }), "image file loads");
ok((await p.locator("table.plain tbody tr").count()) === 2, "table rows");
ok((await p.locator("aside.callout.mistake").count()) === 1, "callout");
ok((await p.locator(".cm-content").innerText()).includes("A[:, None, :]"), "code block");
ok((await p.locator(".toc li").count()) === 3, "contents list has 3 headings");
ok((await p.locator("p a", { hasText: "array shapes" }).getAttribute("href")) === "#/article/shapes", "article link");
await p.click("p a:has-text('Question 030')");
await p.waitForSelector("h1 .id");
ok((await p.locator("h1").innerText()).includes("030"), "question link opens question 030");
await p.goto(base + "#/article/shapes"); await p.waitForSelector("h1:has-text('Array shapes')");
ok((await p.locator("section:has(h2:has-text('Used by')) a").innerText()) === "Broadcasting", "Used by lists dependants");
await p.goto(base + "#/article/nope"); await p.waitForSelector("[role=alert]");
ok(true, "unknown article shows an error");
await p.goto(base); await p.waitForSelector("article.result");
await p.fill("input[type=search]", "030"); await p.waitForFunction(() => document.querySelectorAll("article.result").length > 0 && document.querySelectorAll("article.result").length < 100);
ok((await p.locator("article.result").first().innerText()).includes("Deep lesson available"), "complete lesson shows as available on the index");
await p.goto(base + "#/article/broadcasting"); await p.waitForSelector("h1");
await p.screenshot({ path: process.argv[2] + "/article.png", fullPage: true });
await p.emulateMedia({ colorScheme: "dark" });
await p.screenshot({ path: process.argv[2] + "/article-dark.png", fullPage: true });
const real = errs.filter((e) => !/404/.test(e));
console.log("console errors (excluding expected 404):", real.length ? real : "none");
await b.close();
