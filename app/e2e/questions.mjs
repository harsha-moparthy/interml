// Browser check for the index and question pages. Needs both servers running and playwright-core.
// Run: node questions.mjs <screenshot-dir>   (edit `exe` to your Chromium path)
import { chromium } from "playwright-core";
const PORT = process.env.WEB_PORT || 5173;
const exe = "/mnt/nas/harshamttl/.cache/ms-playwright/chromium-1148/chrome-linux/chrome";
const b = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 1100, height: 800 }, permissions: ["clipboard-read", "clipboard-write"] });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
const ok = (c, msg) => { console.log((c ? "PASS " : "FAIL ") + msg); if (!c) process.exitCode = 1; };
await p.goto("http://127.0.0.1:" + PORT + "/");
await p.waitForSelector("article.result");
ok((await p.locator("article.result").count()) === 1100, "index shows 1,100 questions");
await p.fill("input[type=search]", "316");
await p.waitForFunction(() => document.querySelectorAll("article.result").length > 0 && document.querySelectorAll("article.result").length < 100);
ok((await p.locator("article.result").first().innerText()).includes("Multi-Head"), "search 316 puts multi-head attention first");
await p.locator("article.result a.result-link").first().click();
await p.waitForSelector("h1 .id");
ok((await p.locator("h1").innerText()).includes("316"), "question page opens");
ok((await p.locator(".task").innerText()).length > 20, "original task shown");
ok((await p.locator(".cm-content").count()) === 0 || !(await p.locator("#solution-panel").isVisible()), "solution hidden by default");
const btn = p.getByRole("button", { name: "Show solution" });
ok((await btn.getAttribute("aria-expanded")) === "false", "button aria-expanded=false");
await btn.focus(); await p.keyboard.press("Enter");
await p.waitForSelector(".cm-content");
const api316 = await (await fetch("http://127.0.0.1:" + PORT + "/api/exercises/316/solution")).json();
// The editor draws only the visible lines, so read the full text through Copy.
await p.getByRole("button", { name: "Copy" }).click();
ok((await p.evaluate(() => navigator.clipboard.readText())) === api316.code, "shown solution equals stored solution for 316");
ok(await p.getByRole("button", { name: "Hide solution" }).isVisible(), "button now says Hide solution");
await p.getByRole("button", { name: "Hide solution" }).focus();   // Copy took the focus
await p.keyboard.press("Enter");
ok(!(await p.locator("#solution-panel").isVisible()), "Hide solution hides it");
await p.keyboard.press("Enter");
ok(await p.locator(".cm-content").isVisible(), "show again works");
await p.getByRole("link", { name: /^317 →/ }).click();
await p.waitForFunction(() => document.querySelector("h1")?.innerText.includes("317"));
ok(!(await p.locator("#solution-panel").isVisible()), "next question starts with solution hidden");
ok((await p.locator(".cm-content").count()) === 0, "previous solution is not in the page");
await p.goto("http://127.0.0.1:" + PORT + "/#/question/59");
await p.waitForSelector("h1 .id");
ok((await p.locator(".license").count()) === 1, "repository-derived question 059 shows license note");
await p.goto("http://127.0.0.1:" + PORT + "/#/question/1"); await p.waitForFunction(() => document.querySelector("h1")?.innerText.includes("001"));
ok((await p.locator(".license").count()) === 0, "original question 001 has no license note");
await p.goto("http://127.0.0.1:" + PORT + "/#/question/601");
await p.waitForSelector(".readings li");
ok((await p.locator(".readings li").count()) === 2, "supplemental question shows two technical readings");
ok(await p.getByRole("button", { name: "Show answer guide" }).isVisible(), "supplemental answer guide is available");
await p.getByRole("button", { name: "Show answer guide" }).click();
await p.waitForSelector(".answer-guide");
ok((await p.locator(".answer-guide").innerText()).includes("complete solution"), "supplemental answer guide loads");
await p.screenshot({ path: process.argv[2] + "/q601-readings.png", fullPage: true });
await p.goto("http://127.0.0.1:" + PORT + "/#/question/1101");
await p.waitForSelector("[role=alert]");
ok(true, "unknown question shows an error");
await p.goto("http://127.0.0.1:" + PORT + "/#/question/316");
await p.waitForSelector("h1 .id");
await p.screenshot({ path: process.argv[2] + "/q316.png" });
await p.setViewportSize({ width: 390, height: 800 });
await p.screenshot({ path: process.argv[2] + "/q316-mobile.png" });
console.log("console/page errors:", errs.filter((e) => !e.includes("404 (Not Found)")).length ? errs : "none");
await b.close();
